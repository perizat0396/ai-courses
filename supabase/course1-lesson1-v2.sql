Барлығының жұмыс істеу тәсілі ұқсас: сұрақ жазасыз — жауап аласыз.

## ЖИ-ден қалай сұрау керек
- **Промпт** — жасанды интеллектке жазылған өтініш немесе сұрақ. Қарапайым сөздермен, адаммен сөйлескендей жазыңыз.
- Жақсы промпт төрт сұраққа жауап береді: **не істеу керек? кімге арналған? қандай талаптар бар? қандай түрде?**
- Салыстырыңыз: «Маған мәзір құрастыр» және «Менде тауық еті, қарақұмық және сәбіз бар. Екі адамға арналған, 30 минуттан артық уақыт алмайтын кешкі ас ұсын». Екінші өтініште азық-түлік, адам саны және дайындалу уақыты көрсетілген, сондықтан оның жауабы пайдалырақ болады.
- Жауап ұнамаса, қайта сұраңыз: «Қарапайым тілмен түсіндір», «Қысқартып жаз», «Тағы бірнеше нұсқа ұсын».

> **Екі қауіпсіздік ережесі.** Маңызды ақпаратты тексеріңіз: денсаулық, дәрі-дәрмек, ақша және заң мәселелері бойынша дәрігерден, заңгерден немесе сенімді адамнан кеңес алыңыз. ЖИ-ге ЖСН, құпиясөз, SMS-код, банк картасының нөмірі және үй мекенжайын жібермеңіз.

## Практика: WhatsApp-тағы Meta AI
1. WhatsApp-ты ашыңыз.
