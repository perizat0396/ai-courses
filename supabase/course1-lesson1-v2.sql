## Сабақ туралы қысқаша
Алдымен «ЖИ деген не?» бейнесін көреміз, содан кейін ЖИ көмекшілерімен танысып, өтінішті дұрыс жазуды үйренеміз. Соңында — WhatsApp-тағы Meta AI-мен практика.

## Ең танымал ЖИ көмекшілері

| Көмекші | Компания | Қайдан табуға болады? | Не қажет? |
|---|---|---|---|
| ChatGPT | OpenAI | chatgpt.com сайты және қолданба | тіркелген дұрыс |
| Gemini | Google | gemini.google.com сайты және қолданба | Google аккаунты (Gmail поштасы) |
