3. «Сәлем!» деп жазып, жіберіңіз.
4. Тапсырманы таңдаңыз — құттықтау, мәзір, демалыс жоспары немесе хабарлама. Алдымен қарапайым жазыңыз, содан кейін толық ақпарат қосып, жауапты жақсартуды сұраңыз.

Егер белгіше көрінбесе, WhatsApp қолданбасын Play Market немесе App Store арқылы жаңартыңыз.

