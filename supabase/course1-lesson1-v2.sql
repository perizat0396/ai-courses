## Как просить ИИ
- **Промпт** — это ваша просьба или вопрос к ИИ. Пишите обычными словами, как знакомому человеку.
- Хорошая просьба отвечает на 4 вопроса: **что сделать? для кого? какие условия? в каком виде?**
- Сравните: «Составь мне меню» и «У меня есть курица, гречка и морковь. Предложи ужин для двух человек, не дольше 30 минут». Во второй просьбе есть продукты, количество человек и время — поэтому ответ будет полезнее.
- Ответ не понравился — попросите ещё раз: «Объясни проще», «Сделай короче», «Предложи ещё варианты».

> **Два правила безопасности.** Проверяйте важное: здоровье, лекарства, деньги, законы — уточняйте у врача, юриста или близких. Не отправляйте ИИ ИИН, пароли, коды из СМС, номер карты и домашний адрес.

