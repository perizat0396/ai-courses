## 4. Почему ИИ иногда ошибается
1. **Он составляет правдоподобный текст, а не проверяет факты.** Если точного ответа нет, ИИ может уверенно «придумать» дату, цифру, имя или даже книгу. Это называют **галлюцинацией**.
2. **Его знания заканчиваются в какой-то момент.** Он мог не узнать о событиях последних месяцев.
3. **Он не знает вашего контекста.** На вопрос «сколько стоит проезд?» он не знает, в каком вы городе.
4. **Неточный вопрос — неточный ответ.** Чем подробнее вы спросите, тем лучше ответ.

### Как защититься — 3 простых правила
- **Важное проверяйте**: цифры, даты, законы, здоровье, деньги — по официальным источникам.
- **Спросите ИИ**: «Насколько ты уверен? Где это можно проверить?»
- **Уточняйте**: если ответ странный — переспросите или задайте вопрос иначе.

