## Референстер: ЖИ-ге үлгіні қалай беру және оны қайдан алу
**Референс** — ЖИ бағдар алатын үлгі: тон, құрылым, ұзындық. Бір жақсы үлгі «жанды әрі қызық жаз» деген бір абзац сипаттамадан жақсы жұмыс істейді.

### Нені беру керек
- **3–5 сәтті пост** — өзіңіздікі немесе басқалардікі: сізге және аудиторияға ұнайтындары.
- **Анти-мысал** — нақты не жаман екені белгіленген «қалай болмайды» деген 1–2 мәтін.
- **ЖОО бренд-букі / tone of voice** — бар болса.
- **Фактілер бөлек** — референс мазмұнды емес, стильді береді.

### Қалай беру керек — промт үлгісі
```
Мұнда 3 референс-пост [мәтіндерді қойыңыз немесе файлды тіркеңіз].
Олардан ал: тонды, ұзындықты, құрылымды (хук → пайда → шақыру), оқырманға жүгіну мәнерін.
Алма: фактілерді, атауларды, сөз тіркестерін сөзбе-сөз.
Анти-мысал: [мәтін] — мұнда жаман: кеңсе тілі мен леп белгілері.
Міндет: [ақпараттық себеп] туралы осындай стильде пост жаз.
```
ЖИ-ден алдымен **референстердің стилін сипаттауды** сұраңыз («Осы посттардың ұқсастығын 5 тармақпен сипатта»), содан кейін ғана жазғызыңыз — нәтиже дәлірек болады.

### Қайдан алу керек
| Дереккөз | Нені іздеу керек |
|---|---|
| Әлеуметтік желілеріңіз → статистика (Instagram: «Кәсіби панель») | Қамтуы мен сақталуы ең көп посттар |
| Баспасөз қызметінің мұрағаты, ЖОО сайты | Басшылық мақтаған жаңалықтар |
| Қазақстан мен әлемнің мықты ЖОО-ларының әлеуметтік желілері мен сайттары | Сізде әлі жоқ форматтар |
| Аудиторияңыз оқитын БАҚ пен Telegram-арналар | Тақырыптар, хуктар, беру мәнері |

**Тапқанды бірден сақтаңыз** — Instagram-дағы «Сақталғандарға» немесе «Референстер» деген бір құжатқа. Сәттілерін Claude мен ChatGPT жобасына жүктеңіз (0-модуль), сонда ЖИ оларды әрқашан ескереді.

> Референс — стиль үшін, көшіру үшін емес. Бөтен мәтінді толық жарияламаңыз және өзіңіздікі ретінде көрсетпеңіз.$t$;
