## Референсы: как дать ИИ образец и где его взять
**Референс** — образец, на который ИИ ориентируется: тон, структура, длина. Один хороший образец работает лучше, чем абзац описаний «пиши живо и интересно».

### Что давать
- **3–5 удачных постов** — своих или чужих: тех, что нравятся вам и аудитории.
- **Анти-пример** — 1–2 текста «как не надо» с пометкой, что именно плохо.
- **Бренд-бук / tone of voice вуза** — если есть.
- **Факты отдельно** — референс задаёт стиль, а не содержание.

### Как давать — шаблон промта
```
Вот 3 поста-референса [вставьте тексты или приложите файл].
Возьми из них: тон, длину, структуру (хук → польза → призыв), манеру обращения к читателю.
Не бери: факты, названия, фразы дословно.
Анти-пример: [текст] — здесь плохо: канцелярит и восклицания.
Задача: напиши пост про [инфоповод] в том же стиле.
```
Попросите ИИ сначала **описать стиль референсов** («Опиши в 5 пунктах, чем похожи эти посты»), а уже потом писать — так результат точнее.

### Где брать
| Источник | Что искать |
|---|---|
| Ваши соцсети → статистика (Instagram: «Профессиональная панель») | Посты с наибольшими охватами и сохранениями |
| Архив пресс-службы, сайт вуза | Новости, которые хвалило руководство |
| Соцсети и сайты сильных вузов Казахстана и мира | Форматы, которых у вас ещё нет |
| Медиа и Telegram-каналы, которые читает ваша аудитория | Заголовки, хуки, подача |

**Сохраняйте находки сразу** — в «Сохранённое» в Instagram или в один документ «Референсы». Удачные — загружайте в проект Claude и ChatGPT (модуль 0), и ИИ будет учитывать их всегда.

> Референс — для стиля, не для копирования. Чужой текст целиком не публикуйте и не выдавайте за свой.$t$;
