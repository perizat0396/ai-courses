1. Референстің негізгі кадрларынан **3–5 скриншот** жасаңыз.
2. Оларды Claude-қа тіркеп, сөзбен сипаттаңыз: ұзақтығы, қарқыны, экрандағы мәтін қай жерде, дауыс бар ма.
```
Мұнда референс-роликтің кадрлары [тіркеңіз]. Ұзақтығы 25 сек, 2 секундтан жылдам жалғаулар, ортада ірі мәтін, дауыссыз, ырғақты музыкамен.
Осы роликтің құрылымын секунд бойынша сипатта. Содан кейін [ақпараттық себеп] туралы дәл осындай құрылымда сценарий жаз.
```

> Бөтен роликтегі музыканы пайдаланбаңыз — жариялауға рұқсат етілген CapCut немесе Instagram кітапханасындағы тректерді алыңыз.$t$;
