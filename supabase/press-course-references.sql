```
Вот кадры ролика-референса [приложите]. Длительность 25 сек, быстрые склейки по 2 сек, крупный текст по центру, без голоса, под ритмичную музыку.
Опиши структуру этого ролика по секундам. Затем напиши в такой же структуре сценарий про [инфоповод].
