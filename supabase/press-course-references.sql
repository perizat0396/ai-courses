## Бейнеге арналған референстер
### Қайдан алу керек
- **Instagram Reels және TikTok** — роликтерді «Reels референстері» деген бөлек жинаққа сақтаңыз. ЖОО хэштегтері және «university reels», «campus tour» сұраулары бойынша іздеңіз.
- **YouTube Shorts** — университет арналары.
- **CapCut → Үлгілер** — дайын монтаж ырғағы мен ауысулар.

### ЖИ-ге референсті қалай беру керек
