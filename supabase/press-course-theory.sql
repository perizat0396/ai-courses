## 1. Что такое ИИ-ассистент — простыми словами
Claude и ChatGPT — **языковые модели**. Они прочитали огромное количество текстов и научились продолжать текст так, как его продолжил бы человек. Поэтому они отлично пишут, переписывают, сокращают, переводят и придумывают варианты.

Из этого следуют три важных правила:
1. **ИИ не знает вашего контекста.** Он не знает, что у вас День открытых дверей, кто ректор и какой у вуза тон. Всё это нужно сказать.
2. **ИИ может уверенно ошибаться.** Если данных нет, модель может «додумать» дату, цифру или должность. Это называется **галлюцинацией**. Факты всегда проверяет человек.
3. **Результат зависит от запроса.** Расплывчатый запрос → средний текст. Конкретный запрос → текст, который почти не нужно править.

