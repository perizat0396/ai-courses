## 2. Почему ИИ ошибается
ИИ подбирает **правдоподобный** текст, а не проверенный. Поэтому он может:
- придумать **цифру, дату, должность, название рейтинга**;
- перепутать **имена** и **официальные названия**;
- сослаться на **несуществующий** источник;
- выдать устаревшие сведения.

### Как проверять — 4 шага
1. Попросите ИИ **выписать все факты** из текста: имена, должности, даты, цифры, названия.
2. Сверьте каждый с **первоисточником**: приказ, сайт вуза, организатор.
3. Цифры и рейтинги — только **со ссылкой** на источник.
4. Финальный текст читает **второй человек**.

