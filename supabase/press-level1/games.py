def build(tpl_name, data, key, lang, out):
    tpl = (SL / tpl_name).read_text()
    d = {"lang": lang, "key": key, "ui": data['ui'], "levels": data['levels']}
    js = json.dumps(d, ensure_ascii=False).replace('</', '<\\/')
    html = re.sub(r'(<script id="data" type="application/json">).*?(</script>)', lambda m: m.group(1) + js + m.group(2), tpl, count=1, flags=re.S)
    html = re.sub(r'<title>.*?</title>', '<title>' + data['ui']['title'] + '</title>', html, count=1)
    # широкие скриншоты Claude — во всю ширину карточки
    html = html.replace('</style>', '.refimg img[src*="/lessons/claude/"]{max-width:100%}.refimg img[src*="/brand/"]{max-width:200px;box-shadow:none;border-radius:0}</style>', 1)
    # новый экран начинается только с заголовка — так картинка, шаги и промт одного шага остаются вместе
    old = html[html.index('function screens(l){'):html.index('let STEP=0;')]
    html = html.replace(old, "function screens(l){const out=[];let cur=null;l.blocks.forEach(b=>{if(!cur||b.t==='h'){cur=[b];out.push(cur)}else cur.push(b)});if(l.quiz)out.push('quiz');return out}\n")
    (SL / out).write_text(html)
    n = sum(1 for l in data['levels'] for b in l['blocks'] if b['t'] == 'h')
    print(out, len(data['levels']), 'уровней,', n, 'экранов')

